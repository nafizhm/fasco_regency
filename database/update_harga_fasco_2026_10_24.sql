START TRANSACTION;
UPDATE kavling_peta AS kav
INNER JOIN lokasi_kavling AS lokasi ON lokasi.id = kav.id_lokasi
INNER JOIN fasco_price_update AS harga
    ON UPPER(TRIM(kav.nama_cluster)) = harga.blok
    AND TRIM(COALESCE(NULLIF(TRIM(kav.no), ''), kav.kode_kavling)) REGEXP '^[0-9]+$'
    AND CAST(COALESCE(NULLIF(TRIM(kav.no), ''), kav.kode_kavling) AS UNSIGNED) = harga.nomor
SET kav.luas_bangunan = harga.luas_bangunan,
    kav.tipe_bangunan = harga.luas_bangunan,
    kav.luas_tanah = harga.luas_tanah,
    kav.hrg_jual = harga.harga,
    kav.rincian_biaya = JSON_ARRAY(
        JSON_OBJECT('nama', 'Harga Rumah', 'nilai', harga.harga),
        JSON_OBJECT('nama', 'Kelebihan Tanah', 'nilai', 0)
    )
WHERE UPPER(TRIM(lokasi.nama_kavling)) IN ('FASCO RESIDENCE', 'FASCO REGENCY');
COMMIT;
